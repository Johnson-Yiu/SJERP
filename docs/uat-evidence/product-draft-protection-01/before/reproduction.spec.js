import { execFileSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'
import { expect,test } from '@playwright/test'
test('document pre-repair product draft loss and log reset',async({page},info)=>{
 test.setTimeout(180000);page.setDefaultTimeout(20000)
 const repo=new URL('../../',import.meta.url)
 const f=JSON.parse(execFileSync(process.env.ISOLATED_TEST_PYTHON,[fileURLToPath(new URL('docs/uat-evidence/product-draft-before/seed.py',repo))],{cwd:fileURLToPath(new URL('backend/',repo)),encoding:'utf8'}).replace(/^\uFEFF/,''))
 await page.setViewportSize({width:1366,height:768})
 await page.goto(`/products?detail=${f.product}&tab=suppliers`)
 await page.getByRole('button',{name:'＋ 添加规则',exact:true}).click()
 await page.getByLabel('规则名称',{exact:true}).fill('修复前未保存规则')
 await page.screenshot({path:info.outputPath('before-rule-edited.png')})
 await page.getByRole('button',{name:'总览',exact:true}).click()
 await expect(page.getByTestId('dialog-confirm')).toHaveCount(0)
 await page.goto(`/products?detail=${f.product}&tab=suppliers`)
 await expect(page.getByLabel('规则名称',{exact:true})).toHaveCount(0)
 await page.screenshot({path:info.outputPath('before-rule-lost.png')})
 await page.goto(`/products?detail=${f.product}&tab=skus`)
 await page.locator('.parameter-plan-panel summary').click()
 await page.getByRole('button',{name:'创建参数方案草稿',exact:true}).click()
 await page.getByRole('button',{name:'＋ 新增参数',exact:true}).click()
 await page.getByLabel('参数名称',{exact:true}).fill('修复前未保存参数')
 await page.screenshot({path:info.outputPath('before-plan-edited.png')})
 await page.getByRole('button',{name:'总览',exact:true}).click()
 await expect(page.getByTestId('dialog-confirm')).toHaveCount(0)
 await page.goto(`/products?detail=${f.product}&tab=skus`)
 await page.locator('.parameter-plan-panel summary').click()
 await page.getByRole('button',{name:/继续 V\d+ 草稿/}).click()
 await expect(page.getByLabel('参数名称',{exact:true})).toHaveCount(0)
 await page.screenshot({path:info.outputPath('before-plan-lost.png')})
 await page.getByRole('button',{name:'操作日志',exact:true}).click()
 await page.reload()
 await expect(page.getByRole('button',{name:'总览',exact:true})).toHaveClass(/active/)
 await page.screenshot({path:info.outputPath('before-log-reset.png')})
})
