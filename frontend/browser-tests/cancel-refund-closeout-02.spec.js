import { execFileSync } from 'node:child_process'
import { chromium, expect as baseExpect, test } from '@playwright/test'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const expect = baseExpect.configure({ timeout: 30000 })

test('A closeout real Chrome cash attribution, cancellation retry and partial termination', async ({ baseURL }) => {
  test.setTimeout(1200000)
  test.skip(process.env.ISOLATED_PLAYWRIGHT_TEST_FILE !== 'cancel-refund-closeout-02.spec.js', 'isolated fixture only')
  const repo = fileURLToPath(new URL('../../', import.meta.url))
  const output = path.join(process.env.ISOLATED_PLAYWRIGHT_EVIDENCE_ROOT, 'chrome')
  await mkdir(output, { recursive: true })
  const fixture = JSON.parse(execFileSync(process.env.ISOLATED_TEST_PYTHON,
    [path.join(repo, 'docs/uat-evidence/cancel-refund-closeout-02/seed.py')],
    { cwd: path.join(repo, 'backend'), encoding: 'utf8', env: { ...process.env, PYTHONUTF8: '1' } }))
  const context = await chromium.launchPersistentContext(path.join(process.env.ISOLATED_TEST_ROOT, 'a-close-chrome'), { channel: 'chrome', viewport: { width: 1366, height: 768 } })
  context.setDefaultTimeout(30000)
  const auth = JSON.parse(await readFile(path.join(process.env.ISOLATED_TEST_ROOT, 'codex-auth.json'), 'utf8'))
  await context.addCookies(auth.cookies)
  const settings = context.pages()[0]
  await settings.goto('chrome://settings/appearance', { waitUntil: 'commit' })
  const zoomControl = settings.locator('settings-appearance-page select').filter({ has: settings.locator('option[value="1.25"]') })
  await expect(zoomControl).toBeVisible({ timeout: 90000 })
  const page = await context.newPage()
  const cdp = await context.newCDPSession(page)
  const browser = (await cdp.send('Browser.getVersion')).product
  expect(browser).toMatch(/^Chrome\//)
  const events = [], captures = []
  page.on('response', async r => {
    if (r.request().method() === 'POST' && /refund-cash|\/cancel\/|quantity-adjustments|\/void\/|writeoff/.test(r.url())) {
      events.push({ url: new URL(r.url()).pathname, status: r.status(), request: r.request().postDataJSON(), response: await r.json().catch(() => null) })
    }
  })
  const save = async () => writeFile(path.join(output, 'run.json'), JSON.stringify({ browser, fixture, events, captures }, null, 2))
  const wb = page.getByRole('dialog', { name: '订单工作台' })
  async function openOrder(f) {
    await page.goto(new URL('/orders?search=' + f.number, baseURL).href)
    await page.getByRole('row').filter({ hasText: f.number }).click()
    await expect(wb).toBeVisible()
  }
  async function collect(name, target) {
    for (const zoom of [1, 1.25]) {
      await zoomControl.selectOption(String(zoom))
      for (const [width,height] of [[1366,768],[1920,1080],[390,844]]) {
        await page.setViewportSize({ width,height })
        await expect.poll(() => page.evaluate(() => devicePixelRatio)).toBeCloseTo(zoom, 2)
        if (width===390) await expect.poll(() => page.locator('.sidebar').evaluate(el=>el.getBoundingClientRect().right)).toBeLessThanOrEqual(1)
        await expect(target).toBeVisible()
        await target.scrollIntoViewIfNeeded()
        const financialSummary=target.locator('.payment-card')
        if (await financialSummary.count()) { await financialSummary.scrollIntoViewIfNeeded(); await expect(financialSummary).toBeInViewport() }
        const metrics = await target.evaluate(el => { const r=el.getBoundingClientRect();return { x:r.x,y:r.y,width:r.width,height:r.height,innerWidth,innerHeight,scrollHeight:el.scrollHeight,clientHeight:el.clientHeight } })
        expect(metrics.x).toBeGreaterThanOrEqual(-1)
        expect(metrics.x+metrics.width).toBeLessThanOrEqual(metrics.innerWidth+1)
        const file = `${name}-${width}-${zoom*100}.png`
        await page.screenshot({ path:path.join(output,file) })
        captures.push({ name,width,height,zoom,metrics,file })
        await save()
      }
    }
    await zoomControl.selectOption('1')
    await page.setViewportSize({ width:1366,height:768 })
  }
  async function refund(f, amount, name) {
    await page.goto(new URL('/transactions?search=' + f.receiptNo, baseURL).href)
    await page.getByRole('row').filter({ hasText:f.receiptNo }).getByRole('button',{name:'详情',exact:true}).click()
    await page.getByRole('button',{name:'从本笔登记退款'}).click()
    const form=page.getByRole('dialog',{name:'登记退款'})
    await expect(form.getByLabel('退款对应订单')).toHaveValue(String(f.order))
    await expect(form.getByLabel('退款对应订单').getByRole('option',{name:'未分配预收款'})).toHaveCount(0)
    await form.getByLabel(/实际退款金额/).fill(String(amount))
    await form.getByLabel('退款依据').fill('合成实际原币退款凭证 '+name)
    await form.getByLabel('实际退款凭证').setInputFiles({name:name+'.pdf',mimeType:'application/pdf',buffer:Buffer.from('%PDF-1.4\nSynthetic '+name+'\n%%EOF')})
    await form.getByRole('button',{name:'上传凭证',exact:true}).click()
    await expect(form.getByText(/凭证已上传/)).toBeVisible()
    if(name==='normal-100') await collect('refund-before-submit',form)
    const saved=page.waitForResponse(r=>r.url().endsWith('/refund-cash/') && r.request().method()==='POST')
    await form.getByRole('button',{name:'确认登记',exact:true}).click()
    const response=await saved
    expect(response.status(),await response.text()).toBe(201)
    await expect(form).toBeHidden()
  }
  try {
    await refund(fixture.paid,100,'normal-100')
    await openOrder(fixture.paid)
    await expect(wb.locator('.payment-card')).toContainText(/100\.00/)
    await collect('normal-refund-after',wb)
    await wb.getByRole('button',{name:'取消订单',exact:true}).click()
    await page.getByLabel('取消原因').fill('合成取消后按原收款分次退款')
    const cancelForm=page.locator('form').filter({has:page.getByRole('heading',{name:'取消订单',exact:true})})
    await collect('cancel-before-submit',cancelForm)
    const cancelled=page.waitForResponse(r=>r.url().endsWith('/cancel/') && r.request().method()==='POST')
    await page.getByRole('button',{name:'确认取消',exact:true}).click()
    const cancellation=await cancelled
    expect(cancellation.status(),await cancellation.text()).toBe(200)
    await expect(wb.locator('.payment-card')).toContainText(/待退款.*900\.00/, {timeout:20000})
    await collect('cancel-after',wb)
    await refund(fixture.paid,400,'cancel-400')
    await openOrder(fixture.paid)
    await expect(wb.locator('.payment-card')).toContainText(/待退款.*500\.00/)
    await refund(fixture.paid,500,'cancel-500')
    await openOrder(fixture.paid)
    await expect(wb.locator('.payment-card')).not.toContainText('待退款')
    await collect('cancel-refunds-complete',wb)
    const paidFinal=await (await page.request.get('/api/orders/'+fixture.paid.order+'/workbench/')).json()
    const sourceFinal=await (await page.request.get('/api/transactions/'+fixture.paid.receipt+'/')).json()
    expect(Number(paidFinal.order.total_amount)).toBe(0)
    expect(Number(paidFinal.payment_summary.paid_amount)).toBe(0)
    expect(Number(paidFinal.payment_summary.balance_amount)).toBe(0)
    expect(sourceFinal.status).toBe('confirmed')
    expect(Number(sourceFinal.amount)).toBe(1000)
    expect(sourceFinal.receipt_refunds.map(row=>Number(row.amount)).sort((a,b)=>a-b)).toEqual([100,400,500])
    await writeFile(path.join(output,'refunded-order-and-source.json'),JSON.stringify({order:paidFinal,source:sourceFinal},null,2))
    await openOrder(fixture.partial)
    await wb.getByRole('button',{name:'取消订单',exact:true}).click()
    await page.getByLabel('取消原因').fill('部分已发订单应当保留背景与原因')
    const refused=page.waitForResponse(r=>r.url().endsWith('/cancel/') && r.request().method()==='POST')
    await page.getByRole('button',{name:'确认取消',exact:true}).click()
    expect((await refused).status()).toBe(400)
    await expect(cancelForm.getByRole('alert')).toBeVisible()
    await expect(page.getByLabel('取消原因')).toHaveValue('部分已发订单应当保留背景与原因')
    await collect('cancel-rejection-retained',cancelForm)
    await cancelForm.getByRole('button',{name:'返回',exact:true}).click()
    await expect(wb).toBeVisible()
    await wb.getByRole('button',{name:'调整数量',exact:true}).click()
    const qty=page.getByRole('dialog',{name:'调整订单数量',exact:true})
    await qty.getByRole('checkbox').check()
    await qty.getByLabel('新的基础数量 A-CLOSE-SKU',{exact:true}).fill('40')
    await qty.getByLabel('新的基础数量 A-CLOSE-ZERO',{exact:true}).fill('0')
    await qty.getByLabel('变更原因').fill('合成部分履约终止，保留已发40件')
    await qty.getByRole('button',{name:'预览影响'}).click()
    await expect(qty).toContainText('请先在财务流水')
    await collect('terminate-paid-refund-guidance',qty)
    await qty.getByRole('button',{name:'取消',exact:true}).click()
    await refund(fixture.partial,600,'partial-before-terminate-600')
    await openOrder(fixture.partial)
    await wb.getByRole('button',{name:'调整数量',exact:true}).click()
    await qty.getByRole('checkbox').check()
    await qty.getByLabel('新的基础数量 A-CLOSE-SKU',{exact:true}).fill('40')
    await qty.getByLabel('新的基础数量 A-CLOSE-ZERO',{exact:true}).fill('0')
    await qty.getByLabel('变更原因').fill('实际退回超出履约金额后终止余项')
    await qty.getByRole('button',{name:'预览影响'}).click()
    await expect(qty.getByRole('button',{name:'确认调整'})).toBeEnabled()
    await collect('terminate-before-submit',qty)
    await qty.getByRole('button',{name:'确认调整'}).click()
    const applied=page.waitForResponse(r=>r.url().endsWith('/quantity-adjustments/') && r.request().method()==='POST')
    await page.getByRole('dialog',{name:'确认调整订单数量',exact:true}).getByRole('button',{name:'确认提交',exact:true}).click()
    const adjusted=await applied
    expect(adjusted.status(),await adjusted.text()).toBe(201)
    await expect(qty).toBeHidden()
    await expect(wb).toContainText('已完成')
    await collect('terminate-after',wb)
    const details=await (await page.request.get('/api/orders/'+fixture.partial.order+'/workbench/')).json()
    expect(details.order.status).toBe('completed')
    expect(Number(details.order.total_amount)).toBe(400)
    expect(details.items.map(row=>Number(row.quantity)).sort((a,b)=>a-b)).toEqual([0,40])
    expect(Number(details.fulfillment_summary.shipped_quantity)).toBe(40)
    expect(Number(details.fulfillment_summary.remaining_quantity)).toBe(0)
    expect(Number(details.payment_summary.paid_amount)).toBe(400)
    expect(Number(details.payment_summary.balance_amount)).toBe(0)
    await writeFile(path.join(output,'final-workbench.json'),JSON.stringify(details,null,2))
    for (const key of ['void','correction']) {
      const f=fixture[key]
      await openOrder(f)
      await wb.getByRole('button',{name:'取消订单',exact:true}).click()
      await page.getByLabel('取消原因').fill('合成取消后验证允许的更正不复活应收')
      const cancellation=page.waitForResponse(r=>r.url().endsWith('/cancel/') && r.request().method()==='POST')
      await page.getByRole('button',{name:'确认取消',exact:true}).click()
      expect((await cancellation).status()).toBe(200)
      await expect(page.getByLabel('取消原因')).toBeHidden()
      await page.goto(new URL('/transactions?search='+f.receiptNo,baseURL).href)
      const row=page.getByRole('row').filter({hasText:f.receiptNo})
      if (key==='void') {
        await row.getByRole('button',{name:'作废',exact:true}).click()
        const form=page.getByRole('dialog',{name:'作废财务流水'})
        await form.getByLabel('作废原因').fill('合成取消订单原收款更正作废')
        await collect('cancelled-void-before',form)
        const result=page.waitForResponse(r=>r.url().endsWith('/void/') && r.request().method()==='POST')
        await form.getByRole('button',{name:'确认作废',exact:true}).click()
        expect((await result).status()).toBe(200)
        await expect(form).toBeHidden()
      } else {
        await row.getByRole('button',{name:'详情',exact:true}).click()
        await page.getByRole('button',{name:'更正抹零',exact:true}).click()
        const form=page.getByRole('dialog',{name:'更正授权抹零'})
        await form.getByLabel(/更正金额/).fill('1')
        await form.getByLabel('更正原因').fill('合成取消订单后撤销错误非现金抵减')
        await collect('cancelled-correction-before',form)
        const result=page.waitForResponse(r=>r.url().includes('writeoff') && r.request().method()==='POST')
        await form.getByRole('button',{name:'追加更正',exact:true}).click()
        expect((await result).status()).toBe(201)
        await expect(form).toBeHidden()
      }
      await openOrder(f)
      await expect(wb).toContainText('已取消')
      await collect('cancelled-'+key+'-after',wb)
      const result=await (await page.request.get('/api/orders/'+f.order+'/workbench/')).json()
      expect(result.order.status).toBe('cancelled')
      expect(Number(result.order.total_amount)).toBe(0)
      expect(Number(result.payment_summary.balance_amount)).toBe(0)
      expect(Number(result.payment_summary.paid_amount)).toBe(key==='void'?0:999)
      await writeFile(path.join(output,'cancelled-'+key+'-workbench.json'),JSON.stringify(result,null,2))
    }
    await save()
  } finally { await save(); await context.close() }
})
