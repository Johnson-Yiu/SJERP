import {test,expect} from '@playwright/test'
import {writeFile} from 'node:fs/promises'
test.skip(process.env.ISOLATED_PLAYWRIGHT_TEST_FILE!=='prelaunch-related-order-02.spec.js','Dedicated authenticated isolated Chrome profile required.')
test.setTimeout(120000)
async function post(page,url,data){const token=(await page.context().cookies()).find(c=>c.name==='csrftoken')?.value;const r=await page.request.post('/api'+url,{data,headers:{'X-CSRFToken':token}});expect(r.status(),await r.text()).toBe(201);return r.json()}
for(const [width,height] of [[1366,768],[1920,1080],[390,844]]) test(`related order draft date currency editing and confirmation ${width}`,async({page},info)=>{
 await page.setViewportSize({width,height})
 const customer=await post(page,'/customers/',{code:'REL'+width,name:'合成关联订单客户'+width,country:'CN',contacts:[{name:'合成联系人',email:'synthetic@example.test'}]})
 const category=await post(page,'/categories/',{name:'合成关联分类'+width})
 const product=await post(page,'/products/',{code:'REL'+width,name:'合成关联产品'+width,category:category.id,sales_model_prefix:'REL'+width})
 const sku=await post(page,'/skus/',{product:product.id,sku:'REL'+width,unit:'pcs',default_price:'10',cost_price:'2',currency:'USD',cost_currency:'CNY',sales_model:'REL'+width})
 await page.goto('/customers?detail='+customer.id)
 await page.locator('.detail-tabs').getByRole('button',{name:/订单记录/}).click()
 await page.getByRole('button',{name:'新增订单',exact:true}).click()
 const form=page.locator('.related-create-modal')
 await expect(form.locator('#related-order-status')).toHaveValue('草稿')
 await expect(form.locator('#related-order-status')).toHaveAttribute('readonly','')
 await form.getByRole('checkbox',{name:new RegExp('REL'+width)}).check()
 const qty=form.getByLabel('数量',{exact:true});await qty.fill('3');await qty.hover();await page.mouse.wheel(0,500);await expect(qty).toHaveValue('3')
 const days=form.getByRole('spinbutton',{name:'交期天数'});await days.fill('14');await days.hover();await page.mouse.wheel(0,500);await expect(days).toHaveValue('14')
 await form.locator('.field').filter({has:page.locator('label').filter({hasText:/^币种$/})}).locator('select').selectOption('EUR')
 await expect(form.getByLabel('售价（EUR）')).toBeVisible();await expect(form.getByLabel('成本（CNY）')).toBeVisible()
 await form.getByLabel('售价（EUR）').fill('12');await form.getByLabel('成本（CNY）').fill('2')
 await page.screenshot({path:info.outputPath('related-order-fields.png')})
 const saved=page.waitForResponse(r=>r.url().endsWith('/orders/')&&r.request().method()==='POST')
 await form.getByRole('button',{name:'保存草稿',exact:true}).click();const r=await saved;expect(r.status(),await r.text()).toBe(201);const order=await r.json()
 expect(order.status).toBe('draft');expect(order.currency).toBe('EUR');expect(Number(order.items[0].quantity)).toBe(3);expect(Number(order.items[0].unit_price)).toBe(12)
 expect(Date.parse(order.expected_ship_date)-Date.parse(order.order_date)).toBe(14*86400000)
 await page.goto('/orders?detail='+order.id)
 const workbench=page.getByRole('dialog',{name:'订单工作台'})
 await workbench.getByRole('button',{name:'编辑草稿',exact:true}).click()
 const editor=page.getByRole('dialog',{name:/销售订单草稿/})
 await editor.locator('.line-row input[min="0.01"]').fill('4')
 const updated=page.waitForResponse(r=>r.url().endsWith('/orders/'+order.id+'/')&&r.request().method()==='PUT')
 await editor.getByRole('button',{name:'保存销售订单草稿'}).click();expect((await updated).ok()).toBe(true)
 await page.goto('/orders?detail='+order.id)
 expect(Number((await (await page.request.get('/api/orders/'+order.id+'/')).json()).items[0].quantity)).toBe(4)
 await workbench.getByRole('button',{name:'确认订单',exact:true}).click()
 const confirmed=page.waitForResponse(r=>r.url().endsWith('/confirm/')&&r.request().method()==='POST')
 await page.getByRole('button',{name:'确认继续',exact:true}).click();expect((await confirmed).ok()).toBe(true)
 const read=await (await page.request.get('/api/orders/'+order.id+'/')).json();expect(read.status).toBe('confirmed')
 await writeFile(info.outputPath('order-readback.json'),JSON.stringify(read,null,2));await page.screenshot({path:info.outputPath('related-order-confirmed.png')})
})

test.beforeEach(async({page})=>{page.setDefaultTimeout(30000)})
