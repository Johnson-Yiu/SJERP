import { execFileSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'
import path from 'node:path'
import { expect as baseExpect, test } from '@playwright/test'
const expect=baseExpect.configure({timeout:30000})

test('C editors, batch results and product logs retain real state', async ({ page }, info) => {
  test.skip(process.env.ISOLATED_PLAYWRIGHT_TEST_FILE !== path.basename(fileURLToPath(import.meta.url)), 'Dedicated isolated Chrome profile only.')
  test.setTimeout(600000)
  page.setDefaultTimeout(60000)
  const repository = new URL('../../', import.meta.url)
  const seed = fileURLToPath(new URL('docs/uat-evidence/product-draft-protection-01/seed.py', repository))
  const fixture = JSON.parse(execFileSync(process.env.ISOLATED_TEST_PYTHON, [seed], {cwd:fileURLToPath(new URL('backend/',repository)),encoding:'utf8'}).replace(/^\uFEFF/,''))
  const shot = name => page.screenshot({path:info.outputPath(`${name}.png`)})
  if (process.env.AUDIT_LOG_ENABLED === '1') {
    await page.goto(`/products?detail=${fixture.product}&tab=operation_logs`)
    await expect(page.locator('.operation-log-panel').getByText('暂无操作日志。',{exact:true})).toBeVisible()
    await page.reload()
    await expect(page.locator('.operation-log-panel').getByText('暂无操作日志。',{exact:true})).toBeVisible()
    await shot('audit-enabled-empty-log-reloaded')
  }
  for (const width of [1366,1920,390]) {
    await page.setViewportSize({width,height:width===1366?768:width===1920?1080:844})
    await page.goto(`/products?detail=${fixture.product}&tab=suppliers`)
    await page.getByRole('button',{name:'＋ 添加规则',exact:true}).click()
    const name=page.getByLabel('规则名称',{exact:true})
    await name.fill(`合成能力规则 ${width}`)
    await page.locator('form.editor select').selectOption(String(fixture.supplier))
    await page.getByLabel('共同供货特点',{exact:true}).fill('包装：合成测试纸盒')
    await shot(`rule-filled-${width}`)
    await page.getByRole('button',{name:'预览匹配',exact:true}).click()
    await expect(page.getByText('匹配 2 个现有 SKU：',{exact:false})).toBeVisible()
    await shot(`rule-preview-before-save-${width}`)
    await page.getByRole('button',{name:'预览匹配',exact:true}).press('Enter')
    await expect(page.getByRole('button',{name:'预览匹配',exact:true})).toBeEnabled()
    await page.getByRole('button',{name:'总览',exact:true}).click()
    await page.getByTestId('dialog-cancel').click()
    await expect(name).toHaveValue(`合成能力规则 ${width}`)
    await shot(`rule-retained-${width}`)
    if (width !== 390) {
      await page.getByRole('link',{name:'客户管理',exact:true}).click()
      await expect(page).toHaveURL(/customers/)
      await expect(page.getByTestId('dialog-confirm')).toHaveCount(0)
      await page.getByRole('tab',{name:/C 合成轨道灯产品/}).click()
      await expect(name).toHaveValue(`合成能力规则 ${width}`)
      await page.getByRole('button',{name:'关闭 C 合成轨道灯产品',exact:true}).click()
      await page.getByTestId('dialog-cancel').click()
      await expect(name).toHaveValue(`合成能力规则 ${width}`)
      const dialogEvent=page.waitForEvent('dialog')
      const refresh=page.reload({timeout:5000}).catch(()=>{})
      const refreshDialog=await dialogEvent
      expect(refreshDialog.type()).toBe('beforeunload')
      await refreshDialog.dismiss(); await refresh
      await expect(name).toHaveValue(`合成能力规则 ${width}`)
    }
    // A rejected save must retain values and the dirty guard.
    await page.route('**/api/supplier-capabilities/', async route => route.request().method()==='POST' ? route.fulfill({status:400,json:{detail:'合成保存失败，请重试'}}) : route.continue())
    await page.getByRole('button',{name:'保存规则',exact:true}).click()
    await expect(name).toHaveValue(`合成能力规则 ${width}`)
    await page.getByRole('button',{name:'总览',exact:true}).click()
    await page.getByTestId('dialog-cancel').click()
    await page.unroute('**/api/supplier-capabilities/')
    await page.getByRole('button',{name:'保存规则',exact:true}).click()
    await expect(name).toHaveCount(0)
    const rules=await (await page.request.get(`/api/supplier-capabilities/?product=${fixture.product}`)).json()
    expect((rules.results||rules).some(rule=>rule.name===`合成能力规则 ${width}` && rule.characteristics['包装']==='合成测试纸盒')).toBeTruthy()
    await shot(`rule-saved-${width}`)
    await page.getByRole('button',{name:'＋ 添加规则',exact:true}).click()
    await name.fill('明确放弃的合成规则')
    await page.getByRole('button',{name:'总览',exact:true}).click()
    await page.getByTestId('dialog-confirm').click()
    await expect(name).toHaveCount(0)
    await expect(page.getByTestId('dialog-confirm')).toHaveCount(0)
    await page.getByRole('button',{name:'操作日志',exact:true}).click()
    await expect(page).toHaveURL(/tab=operation_logs/)
    await page.reload()
    await expect(page.getByRole('button',{name:'操作日志',exact:true})).toHaveClass(/active/)
    await expect(page.locator('.operation-log-panel')).toBeVisible()
    await shot(`log-reopened-${width}`)
    await page.goto(`/products?detail=${fixture.product}&tab=skus`)
    await page.locator('.parameter-plan-panel summary').click()
    await page.getByRole('button',{name:/创建参数方案草稿|继续 V\d+ 草稿/}).click()
    await expect(page.locator('.parameter-plan-panel .editor')).toBeVisible()
    if (await page.getByLabel('参数名称',{exact:true}).count()===0) await page.getByRole('button',{name:'＋ 新增参数',exact:true}).click()
    const parameter=page.getByLabel('参数名称',{exact:true}).first()
    await parameter.fill(`合成参数 ${width}`)
    await page.getByRole('button',{name:'总览',exact:true}).click()
    await page.getByTestId('dialog-cancel').click()
    await expect(parameter).toHaveValue(`合成参数 ${width}`)
    await page.getByRole('button',{name:/继续 V\d+ 草稿/}).click()
    await page.getByTestId('dialog-cancel').click()
    await expect(parameter).toHaveValue(`合成参数 ${width}`)
    await shot(`plan-retained-${width}`)
    if (width !== 390) {
      await page.getByRole('button',{name:'关闭 C 合成轨道灯产品',exact:true}).click()
      await page.getByTestId('dialog-cancel').click()
      await expect(parameter).toHaveValue(`合成参数 ${width}`)
    }
    await page.route(`**/api/products/${fixture.product}/sku-plan/`, route=>route.request().method()==='PATCH'?route.fulfill({status:400,json:{detail:'合成方案保存失败'}}):route.continue())
    await page.getByRole('button',{name:'保存草稿并分析影响',exact:true}).click()
    await expect(page.getByText('合成方案保存失败',{exact:true})).toBeVisible()
    await page.getByRole('button',{name:'总览',exact:true}).click()
    await page.getByTestId('dialog-cancel').click()
    await expect(parameter).toHaveValue(`合成参数 ${width}`)
    await page.unroute(`**/api/products/${fixture.product}/sku-plan/`)
    await page.getByRole('button',{name:'保存草稿并分析影响',exact:true}).click()
    await expect(page.getByRole('heading',{name:'发布前核对',exact:true})).toBeVisible()
    const plan=await (await page.request.get(`/api/products/${fixture.product}/sku-plan/`)).json()
    expect(plan.plans.find(p=>p.status==='draft').definitions[0].name).toBe(`合成参数 ${width}`)
    await shot(`plan-saved-readback-${width}`)
    await page.getByRole('button',{name:'总览',exact:true}).click()
    await expect(page.getByTestId('dialog-confirm')).toHaveCount(0)
    await page.goto(`/products?detail=${fixture.product}&tab=skus`)
    await page.locator('.parameter-plan-panel summary').click()
    await page.getByRole('button',{name:/继续 V\d+ 草稿/}).click()
    await expect(parameter).toHaveValue(`合成参数 ${width}`)
    await parameter.fill('明确放弃的合成参数')
    await page.getByRole('button',{name:'总览',exact:true}).click()
    await page.getByTestId('dialog-confirm').click()
    await expect(parameter).toHaveCount(0)
    await expect(page.getByTestId('dialog-confirm')).toHaveCount(0)
  }
  await page.setViewportSize({width:1366,height:768})
  await page.goto(`/products?detail=${fixture.product}&tab=skus`)
  const rows=page.locator('.candidate-table tbody tr')
  await expect(rows).toHaveCount(2)
  const checkbox=page.locator('.candidate-table thead input')
  await checkbox.scrollIntoViewIfNeeded()
  const box=await checkbox.boundingBox()
  await page.mouse.click(box.x+1,box.y+box.height/2)
  await expect(checkbox).toBeChecked()
  // Inject exactly one rejection; the other PATCH and all readbacks use the real isolated API.
  const failed=`**/api/skus/${fixture.skus[1]}/`
  await page.route(failed,route=>route.request().method()==='PATCH'?route.fulfill({status:400,json:{detail:'合成停用失败'}}):route.continue())
  await page.getByRole('button',{name:'停用 2 项',exact:true}).click()
  await page.getByTestId('dialog-confirm').click()
  await expect(page.getByText(/成功 1 项，失败 1 项/)).toBeVisible()
  await expect(page.getByText('C-SKU-2：合成停用失败',{exact:true})).toBeVisible()
  await expect(rows).toHaveCount(1)
  await expect(page.getByRole('checkbox',{name:'选择 C-SKU-2',exact:true})).toBeChecked()
  expect((await (await page.request.get(`/api/skus/${fixture.skus[0]}/`)).json()).active).toBe(false)
  expect((await (await page.request.get(`/api/skus/${fixture.skus[1]}/`)).json()).active).toBe(true)
  await shot('batch-partial-real-readback')
  await page.getByRole('button',{name:'停用 1 项',exact:true}).click()
  await page.getByTestId('dialog-confirm').click()
  await expect(page.getByText(/成功 0 项，失败 1 项/)).toBeVisible()
  await shot('batch-total-failure-retained')
  await page.unroute(failed)
  await page.getByRole('button',{name:'停用 1 项',exact:true}).click()
  await page.getByTestId('dialog-confirm').click()
  await expect(page.getByText('已停用 1 项 SKU。',{exact:true})).toBeVisible()
  expect((await (await page.request.get(`/api/skus/${fixture.skus[1]}/`)).json()).active).toBe(false)
  await page.getByLabel('显示已停用',{exact:false}).check()
  await page.locator('.candidate-table thead input').check()
  await page.getByRole('button',{name:'重新启用 2 项',exact:true}).click()
  await page.getByTestId('dialog-confirm').click()
  await expect(page.getByText('已启用 2 项 SKU。',{exact:true})).toBeVisible()
  for (const id of fixture.skus) expect((await (await page.request.get(`/api/skus/${id}/`)).json()).active).toBe(true)
  await shot('batch-success-real-readback')
  await rows.first().locator('input[type=checkbox]').check()
  await page.getByRole('button',{name:'批量绑定供应商',exact:true}).click()
  const binding=page.getByRole('dialog',{name:'批量绑定供应商',exact:true})
  await binding.getByRole('switch').check()
  await binding.getByLabel('选择C 合成照明供应商',{exact:true}).check()
  await binding.getByRole('button',{name:'关闭',exact:true}).click()
  await page.getByTestId('dialog-cancel').click()
  await expect(binding.getByLabel('选择C 合成照明供应商',{exact:true})).toBeChecked()
  await expect(binding.getByRole('button',{name:'关闭',exact:true})).toBeFocused()
  await binding.getByRole('button',{name:'关闭',exact:true}).click()
  await page.getByTestId('dialog-confirm').click()
  await expect(binding).toHaveCount(0)
  await expect(page.getByRole('button',{name:'批量绑定供应商',exact:true})).toBeFocused()
  await page.getByRole('button',{name:'批量绑定供应商',exact:true}).click()
  await binding.getByRole('switch').check()
  await binding.getByLabel('选择C 合成照明供应商',{exact:true}).check()
  await binding.getByRole('button',{name:'保存候选供应商',exact:true}).click()
  await expect(binding).toHaveCount(0)
  const savedPool=await (await page.request.get(`/api/products/${fixture.product}/supplier-candidate-pool/`)).json()
  expect(savedPool.rows.find(row=>row.sku_id===fixture.skus[0]).candidate_source_types).toContain('manual')
  await expect(page.getByTestId('dialog-confirm')).toHaveCount(0)
  await shot('binding-saved-real-readback')
  await page.getByRole('button',{name:'关闭 C 合成轨道灯产品',exact:true}).click()
  await expect(page.getByTestId('dialog-confirm')).toHaveCount(0)
  await shot('binding-single-confirm-closed')
})

test.afterEach(async ({page}, info)=> { if(info.status!==info.expectedStatus) await page.screenshot({path:info.outputPath('failure.png')}) })
