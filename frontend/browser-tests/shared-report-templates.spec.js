import { test, expect } from '@playwright/test'
import { mockSharedTemplateApi } from './reporting-fixtures.js'

async function blockOptionalGoogleFonts(page) {
  await page.route('https://fonts.googleapis.com/**', route => route.abort())
  await page.route('https://fonts.gstatic.com/**', route => route.abort())
}

test('separate manager and employee sessions share only the published query definition', async ({ browser }) => {
  const sharedState = { templates: [], nextId: 1 }
  const managerContext = await browser.newContext({ viewport: { width: 1440, height: 1000 } })
  const manager = await managerContext.newPage()
  await blockOptionalGoogleFonts(manager)
  await mockSharedTemplateApi(manager, sharedState, 'manager')
  await manager.goto('/reports')
  await expect(manager.getByRole('button', { name: '根据当前查询创建', exact: true })).toBeEnabled()
  await manager.getByRole('button', { name: '根据当前查询创建', exact: true }).click()
  await manager.locator('.template-editor input').first().fill('团队销售模板')
  await manager.getByRole('button', { name: '保存草稿', exact: true }).click()
  await expect(manager.locator('.template-card')).toHaveCount(1)
  await expect(manager.locator('.template-card')).toContainText('草稿')
  await manager.locator('.template-card').getByRole('button', { name: '发布', exact: true }).click()
  await expect(manager.locator('.template-card')).toContainText('已发布')

  const employeeContext = await browser.newContext({ viewport: { width: 700, height: 1000 } })
  const employee = await employeeContext.newPage()
  await blockOptionalGoogleFonts(employee)
  await mockSharedTemplateApi(employee, sharedState, 'employee')
  await employee.goto('/reports')
  await expect(employee.locator('.template-card')).toHaveCount(1)
  await expect(employee.locator('.template-card')).toContainText('团队销售模板')
  await expect(employee.locator('.template-card').getByRole('button', { name: '编辑', exact: true })).toHaveCount(0)
  await employee.locator('.template-card').getByRole('button', { name: '使用模板', exact: true }).click()
  await expect(employee).toHaveURL(/shared_template=1/)
  await employee.getByRole('button', { name: '保存为图表块', exact: true }).click()
  await expect(employee.locator('.saved-block')).toHaveCount(1)
  await employee.screenshot({ path: '../docs/uat-evidence/iss-042-shared-reports/employee-700px.png', fullPage: true })

  await manager.locator('.template-card').getByRole('button', { name: '编辑', exact: true }).click()
  await manager.locator('.template-editor input').first().fill('团队销售模板（已更新）')
  await manager.getByRole('button', { name: '保存修改', exact: true }).click()
  await employee.reload()
  await expect(employee.locator('.template-card')).toContainText('团队销售模板（已更新）')
  await manager.locator('.template-card').getByRole('button', { name: '操作记录', exact: true }).click()
  await expect(manager.locator('.template-history')).toContainText('操作记录')
  await manager.locator('.template-history').getByRole('button', { name: '关闭', exact: true }).click()
  await manager.screenshot({ path: '../docs/uat-evidence/iss-042-shared-reports/manager-1440px.png', fullPage: true })
  await manager.setViewportSize({ width: 1024, height: 1000 })
  await manager.screenshot({ path: '../docs/uat-evidence/iss-042-shared-reports/manager-1024px.png', fullPage: true })

  sharedState.conflictNext = 'unpublish'
  await manager.locator('.template-card').getByRole('button', { name: '取消发布', exact: true }).click()
  await expect(manager.getByRole('alert')).toContainText('确认取消发布')
  await manager.getByRole('button', { name: '确认', exact: true }).click()
  await expect(manager.getByRole('status')).toContainText('已被其他操作更新，请刷新列表后重试')
  await expect(manager.locator('.template-card')).toContainText('已发布')
  await manager.locator('.template-card').getByRole('button', { name: '取消发布', exact: true }).click()
  await manager.getByRole('button', { name: '确认', exact: true }).click()
  await employee.reload()
  await expect(employee.locator('.template-card')).toHaveCount(0)
  await expect(employee.locator('.saved-block')).toHaveCount(1)

  await manager.locator('.template-card').getByRole('button', { name: '发布', exact: true }).click()
  await expect(manager.locator('.template-card')).toContainText('已发布')
  await manager.locator('.template-card').getByRole('button', { name: '删除', exact: true }).click()
  await manager.getByRole('button', { name: '确认', exact: true }).click()
  await expect(manager.locator('.template-card')).toHaveCount(0)
  await employee.reload()
  await expect(employee.locator('.template-card')).toHaveCount(0)
  await expect(employee.locator('.saved-block')).toHaveCount(1)
  await employee.screenshot({ path: '../docs/uat-evidence/iss-042-shared-reports/employee-700px-after-delete.png', fullPage: true })
  await managerContext.close(); await employeeContext.close()
})
