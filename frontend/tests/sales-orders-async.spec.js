// @vitest-environment jsdom
import { afterEach, beforeEach, expect, it, vi } from 'vitest'
import { mount, flushPromises } from '@vue/test-utils'
import { createMemoryHistory, createRouter } from 'vue-router'
import DocumentPage from '../src/views/DocumentPage.vue'

const mocks = vi.hoisted(() => ({ listAll: vi.fn(), get: vi.fn(), post: vi.fn(), confirmDialog: vi.fn() }))
vi.mock('../src/api', () => ({ listAll: mocks.listAll, api: { get: mocks.get, post: mocks.post }, downloadQuoteExport: vi.fn() }))
vi.mock('../src/dialogs', () => ({ confirmDialog: mocks.confirmDialog }))
let wrapper
const deferred = () => { let resolve, reject; const promise = new Promise((yes, no) => { resolve = yes; reject = no }); return { promise, resolve, reject } }
const row = name => ({ id: 1, order_no: name, customer_name: '测试客户', status: 'draft', items: [], currency: 'USD' })
beforeEach(() => {
  vi.clearAllMocks()
  mocks.confirmDialog.mockResolvedValue(true)
  mocks.listAll.mockImplementation(async url => url === '/customers/' ? [{ id: 1, name: '测试客户' }] : url === '/quotes/' ? [{ id: 7, quote_no: 'QT-7', status: 'draft' }] : [])
})
afterEach(() => wrapper?.unmount())
async function page() {
  const router = createRouter({ history: createMemoryHistory(), routes: [{ path: '/:pathMatch(.*)*', component: { template: '<main />' } }] })
  await router.push('/orders')
  wrapper = mount(DocumentPage, { props: { type: 'orders' }, global: { plugins: [router], directives: { 'money-input': {} }, stubs: { OrderDetailModal: true, QuoteDetailModal: true, SkuPickerPanel: true } } })
  await flushPromises()
  return router
}
it.each(['success', 'failure'])('ignores stale list %s while the latest request remains pending', async outcome => {
  const router = await page()
  const old = deferred(), latest = deferred()
  mocks.listAll.mockImplementation((_url, options) => options?.params?.status === 'confirmed' ? old.promise : latest.promise)
  await router.push('/orders?status=confirmed'); await flushPromises()
  await router.push('/orders?status=completed'); await flushPromises()
  if (outcome === 'success') old.resolve([row('OLD')]); else old.reject(new Error('迟到的错误'))
  await flushPromises()
  expect(wrapper.text()).not.toContain('OLD')
  expect(wrapper.text()).not.toContain('迟到的错误')
  expect(wrapper.findComponent({ name: 'PageLoadState' }).props('loading')).toBe(true)
  latest.resolve([row('CURRENT')]); await flushPromises()
  expect(wrapper.text()).toContain('CURRENT')
  expect(wrapper.findComponent({ name: 'PageLoadState' }).props('loading')).toBe(false)
})
it('does not replace the latest list when an older response arrives last', async () => {
  const router = await page(), old = deferred()
  mocks.listAll.mockImplementation((_url, options) => options?.params?.status === 'confirmed' ? old.promise : Promise.resolve([row('CURRENT')]))
  await router.push('/orders?status=confirmed'); await flushPromises()
  await router.push('/orders?status=completed'); await flushPromises()
  old.resolve([row('OLD')]); await flushPromises()
  expect(wrapper.text()).toContain('CURRENT')
  expect(wrapper.text()).not.toContain('OLD')
})
it('ignores an old empty-state fallback while the latest request is pending', async () => {
  const router = await page(), fallback = deferred(), latest = deferred()
  mocks.listAll.mockImplementation((_url, options) => !options ? fallback.promise : options.params.status === 'confirmed' ? Promise.resolve([]) : latest.promise)
  await router.push('/orders?status=confirmed'); await flushPromises()
  await router.push('/orders?status=completed'); await flushPromises()
  fallback.resolve([row('EXISTS')]); await flushPromises()
  expect(wrapper.findComponent({ name: 'PageLoadState' }).props('loading')).toBe(true)
  latest.resolve([row('CURRENT')]); await flushPromises()
  expect(wrapper.text()).toContain('CURRENT')
})
it('shows a current request error and allows retry', async () => {
  const router = await page()
  mocks.listAll.mockRejectedValueOnce(new Error('当前请求失败'))
  await router.push('/orders?status=confirmed'); await flushPromises()
  expect(wrapper.text()).toContain('当前请求失败')
  mocks.listAll.mockResolvedValue([row('RETRY')])
  await wrapper.findAll('button').find(button => button.text() === '重新加载').trigger('click'); await flushPromises()
  expect(wrapper.text()).toContain('RETRY')
  expect(wrapper.text()).not.toContain('当前请求失败')
})
it('ignores a source quote error after closing the order editor', async () => {
  await page()
  await wrapper.findAll('button').find(button => button.text() === '新建订单').trigger('click'); await flushPromises()
  const pending = deferred(); mocks.get.mockReturnValue(pending.promise)
  await wrapper.get('[aria-label="来源报价（可选）"]').setValue('7'); await flushPromises()
  await wrapper.get('.modal-head button').trigger('click'); await flushPromises()
  pending.reject(new Error('迟到报价错误')); await flushPromises()
  expect(wrapper.find('.modal-backdrop').exists()).toBe(false)
  expect(wrapper.text()).not.toContain('迟到报价错误')
})
it('blocks closing and navigation during order save and allows save completion navigation', async () => {
  const router = await page()
  await wrapper.findAll('button').find(button => button.text() === '新建订单').trigger('click'); await flushPromises()
  mocks.get.mockResolvedValue({ data: { customer: 1, quote: 7, order_date: '2026-11-04', currency: 'USD', exchange_rate: '7', shipping_fee: 0, discount: 0, notes: '', items: [{ sku: 1, quantity: '1', unit_price: '10' }] } })
  await wrapper.get('[aria-label="来源报价（可选）"]').setValue('7'); await flushPromises()
  const pending = deferred(); mocks.post.mockReturnValue(pending.promise)
  await wrapper.get('form.modal').trigger('submit'); await flushPromises()
  expect(mocks.post).toHaveBeenCalledTimes(1)
  await wrapper.get('.modal-head button').trigger('click'); await flushPromises()
  expect(wrapper.find('form.modal').exists()).toBe(true)
  await router.push('/elsewhere')
  expect(router.currentRoute.value.path).toBe('/orders')
  pending.resolve({ data: { id: 99 } }); await flushPromises()
  expect(wrapper.find('form.modal').exists()).toBe(false)
  expect(router.currentRoute.value.query.detail).toBe('99')
})
it('keeps order data after save failure and releases the close guard', async () => {
  await page()
  await wrapper.findAll('button').find(button => button.text() === '新建订单').trigger('click'); await flushPromises()
  mocks.get.mockResolvedValue({ data: { customer: 1, quote: 7, order_date: '2026-11-04', currency: 'USD', exchange_rate: '7', shipping_fee: 0, discount: 0, notes: '保留的草稿', items: [{ sku: 1, quantity: '1', unit_price: '10' }] } })
  await wrapper.get('[aria-label="来源报价（可选）"]').setValue('7'); await flushPromises()
  mocks.post.mockRejectedValue(new Error('保存失败'))
  await wrapper.get('form.modal').trigger('submit'); await flushPromises()
  expect(wrapper.find('form.modal').exists()).toBe(true)
  expect(wrapper.text()).toContain('保存失败')
  expect(wrapper.get('textarea').element.value).toBe('保留的草稿')
  await wrapper.get('.modal-head button').trigger('click'); await flushPromises()
  expect(wrapper.find('form.modal').exists()).toBe(false)
})
