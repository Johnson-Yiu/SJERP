import { beforeEach, expect, it, vi } from 'vitest'
import { flushPromises, mount } from '@vue/test-utils'
import ProductSkuManagement from '../src/components/ProductSkuManagement.vue'
const { api, listAll } = vi.hoisted(() => ({ api: { get: vi.fn(), post: vi.fn(), patch: vi.fn(), delete: vi.fn() }, listAll: vi.fn() }))
vi.mock('../src/api', () => ({ api, listAll }))
const definition = { category_id: 1, key: 'voltage', name: '电压', unit: 'V', default_value: '', include_in_sku: true, include_in_sales_model: false, required: false, uppercase: false }
const draft = { id: 1, version: 2, status: 'draft', definitions: [definition], assignments: {}, updated_at: 'today' }
const state = { definitions: [definition], plans: [], relationships: [], skus: [{ id: 1, sku: 'SKU1', display_name_cn: '灯带24V', parameter_values: { '1:voltage': '24' } }] }
const click = async (w, text) => { await w.findAll('button').find(b => b.text().includes(text)).trigger('click'); await flushPromises() }
it('shows one SKU list and permanent supplier maintenance with archive navigation', async () => {
  const w = mount(ProductSkuManagement, { props: { productId: 1 } }); await flushPromises()
  expect(w.findAll('.candidate-table').length).toBe(1)
  expect(w.find('.candidate-pool-card').exists()).toBe(true)
  expect(w.find('.switcher').exists()).toBe(false)
  expect(w.findAll('.candidate-table tbody tr').length).toBe(1)
  expect(w.find('.candidate-table').text()).toContain('12')
  await click(w, 'SKU1')
  expect(w.emitted('drill')[0]).toEqual([{ id: 1, _target_entity: 'skus' }])
  await w.find('.inline-check input').setValue(true)
  expect(w.findAll('.candidate-table tbody tr').length).toBe(2)
  expect(w.find('.inactive-sku-row').text()).toContain('已停用')
  w.unmount()
})
it('all parameter values keeps the list and filtering clears bulk selection', async () => {
  const w = mount(ProductSkuManagement, { props: { productId: 1 } }); await flushPromises()
  await w.find('.candidate-table tbody input').setValue(true)
  expect(w.text()).toContain('停用 1 项')
  await w.find('.pool-parameter-filters input').setValue(true)
  expect(w.findAll('.candidate-table tbody tr').length).toBe(1)
  expect(w.text()).not.toContain('停用 1 项')
  w.unmount()
})
it('opens the batch supplier binding flow for selected active SKUs', async () => {
  const w = mount(ProductSkuManagement, { props: { productId: 1 } }); await flushPromises()
  await w.find('.candidate-table tbody input').setValue(true)
  await click(w, '批量绑定供应商')
  expect(w.findComponent({ name: 'SupplierBatchBindingDrawer' }).exists()).toBe(true)
  w.unmount()
})
it('rules workspace avoids duplicating the SKU list and supplier allocation panel', async () => {
  const w = mount(ProductSkuManagement, { props: { productId: 1, initialTab: 'rules' } }); await flushPromises()
  expect(w.find('.candidate-table').exists()).toBe(false)
  expect(w.find('.candidate-pool-card').exists()).toBe(false)
  expect(w.find('.rules-panel').attributes('open')).toBeDefined()
  w.unmount()
})
it('reloads SKU data after an archive edit without clearing the keyword', async () => {
  const w = mount(ProductSkuManagement, { props: { productId: 1, refreshKey: 0 } }); await flushPromises()
  await w.find('.pool-filters input').setValue('灯带')
  const before = listAll.mock.calls.filter(([url]) => url === '/skus/').length
  await w.setProps({ refreshKey: 1 }); await flushPromises()
  expect(listAll.mock.calls.filter(([url]) => url === '/skus/').length).toBe(before + 1)
  expect(w.find('.pool-filters input').element.value).toBe('灯带')
  w.unmount()
})
it('bulk status writes only selected SKU and reports API failure', async () => {
  const confirm = vi.spyOn(window, 'confirm').mockReturnValue(true)
  const w = mount(ProductSkuManagement, { props: { productId: 1 } }); await flushPromises()
  api.patch.mockRejectedValueOnce(new Error('该 SKU 不允许停用'))
  await w.find('.candidate-table tbody input').setValue(true)
  await click(w, '停用 1 项')
  expect(api.patch).toHaveBeenCalledWith('/skus/1/', { active: false })
  expect(w.text()).toContain('1 个操作失败')
  expect(w.text()).toContain('该 SKU 不允许停用')
  w.unmount(); confirm.mockRestore()
})
beforeEach(() => {
  vi.clearAllMocks()
  api.get.mockImplementation((url, config) => Promise.resolve({ data: config?.params?.eligible ? [{ id: 2, name: '供应商甲', code: 'SUP-1', category_match: true, supply_category_names: [] }] : url.includes('supplier-candidate-pool') ? { rows: [], parameter_options: [{ key: '1:voltage', name: '电压', values: ['24'] }], sku_total: 1, with_candidates: 0, coverage_rate: 0 } : url.includes('supplier-candidates') ? { candidates: [], overrides: [] } : structuredClone(state) }))
  listAll.mockImplementation(url => Promise.resolve(url === '/skus/' ? [{ ...structuredClone(state.skus[0]), active: true, unit: 'm', stock_quantity: 12, cost_price: '2', default_price: '4', currency: 'USD' }, { id: 3, sku: 'OLD', display_name_cn: '旧灯带', active: false }] : url.includes('capabilities') ? [] : [{ id: 2, name: '供应商甲' }]))
  api.post.mockImplementation(url => Promise.resolve({ data: url.endsWith('analyze/') ? { stale: false, missing: [], groups: [], current_count: 1, result_count: 1, new_count: 0 } : structuredClone(draft) }))
  api.patch.mockImplementation((url, data) => Promise.resolve({ data: { ...data, updated_at: 'saved' } }))
})
it('saves a rule with filters and traits without creating supplier SKU records', async () => {
  const w = mount(ProductSkuManagement, { props: { productId: 1, initialTab: 'rules' } }); await flushPromises()
  await click(w, '添加规则')
  const inputs = w.findAll('form input')
  await inputs[0].setValue('常规灯带'); await w.find('form select').setValue('2')
  await inputs[1].setValue('12、24'); await w.find('textarea').setValue('背胶：3M')
  await w.find('form').trigger('submit'); await flushPromises()
  expect(api.post).toHaveBeenCalledWith('/supplier-capabilities/', expect.objectContaining({ filters: { '1:voltage': ['12', '24'] }, characteristics: { 背胶: '3M' } }))
  expect(api.post.mock.calls.some(([url]) => url === '/supplier-skus/')).toBe(false)
  w.unmount()
})
it('editing a reviewed draft disables publish until another analysis', async () => {
  const w = mount(ProductSkuManagement, { props: { productId: 1 } }); await flushPromises()
  await w.find('.parameter-plan-panel summary').trigger('click'); await click(w, '创建参数方案草稿'); await click(w, '保存草稿并分析影响')
  const publishButton = () => w.findAll('button').find(b => b.text().includes('确认以上结果'))
  expect(publishButton().attributes('disabled')).toBeUndefined()
  await w.find('input[aria-label="参数名称"]').setValue('工作电压')
  expect(publishButton().attributes('disabled')).toBeDefined()
  await click(w, '保存草稿并分析影响')
  expect(publishButton().attributes('disabled')).toBeUndefined()
  w.unmount()
})
it('split controls clone reactive values and submit two variants', async () => {
  const w = mount(ProductSkuManagement, { props: { productId: 1 } }); await flushPromises()
  await w.find('.parameter-plan-panel summary').trigger('click'); await click(w, '创建参数方案草稿'); await click(w, '拆分一个实际组合')
  const values = w.findAll('.assignment input')
  expect(values.length).toBe(2)
  await values[1].setValue('12'); await click(w, '保存草稿并分析影响')
  expect(api.patch.mock.calls.at(-1)[1].assignments['1']).toEqual([{ '1:voltage': '24' }, { '1:voltage': '12' }])
  w.unmount()
})
