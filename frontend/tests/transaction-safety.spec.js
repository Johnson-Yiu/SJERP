import { setAccessOperator } from '../src/accessControl'
// @vitest-environment jsdom
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { flushPromises, mount } from '@vue/test-utils'
import { createMemoryHistory, createRouter } from 'vue-router'
import TransactionPage from '../src/views/TransactionPage.vue'
import { dialogState, resolveDialog } from '../src/dialogs'

const financeAccount = id => setAccessOperator({ authenticated: true, user_id: id, has_all_permissions: true })
const savedKey = key => `sunjack:finance-attempt:v2:user:101:${key}`
beforeEach(() => { window.localStorage.clear(); financeAccount(101) })

const mocks = vi.hoisted(() => ({ post: vi.fn(), listAll: vi.fn() }))
vi.mock('../src/api', () => ({ api: { post: mocks.post }, listAll: mocks.listAll }))
let wrapper, router
const button = name => wrapper.findAll('button').find(b => b.text() === name)
const dialog = () => wrapper.get('form.dialog')
async function open() { await button('新增记账').trigger('click'); await flushPromises() }
async function submit() { await dialog().trigger('submit'); await flushPromises() }
async function fill() {
  await dialog().find('select').setValue('customer_receipt')
  await dialog().get('input[placeholder="客户或订单号"]').setValue('SO-FUP')
  await flushPromises()
  await dialog().get('button.order').trigger('click')
  await dialog().find('input[type="number"]').setValue('12.34')
  await dialog().findAll('input[type="number"]')[1].setValue('7.123456')
  await dialog().findAll('fieldset').at(-1).findAll('input').at(-1).setValue('保留备注')
}
beforeEach(async () => {
  vi.clearAllMocks()
  window.sessionStorage.clear()
  mocks.post.mockResolvedValue({ data: {} })
  mocks.listAll.mockImplementation(async url => url === '/orders/' ? [{ id: 7, order_no: 'SO-FUP', customer: 11, customer_name: '合成客户', currency: 'USD', exchange_rate: '7.1', status: 'confirmed', total_amount: '500' }] : url === '/customers/' ? [{ id: 11, name: '合成客户' }] : [])
  router = createRouter({ history: createMemoryHistory(), routes: ['/transactions', '/orders'].map(path => ({ path, component: { template: '<div />' } })) })
  await router.push('/transactions')
  wrapper = mount(TransactionPage, { global: { plugins: [router], directives: { 'money-input': {} } } })
  await flushPromises()
})
afterEach(async () => { if (dialogState.current) { resolveDialog(false); await flushPromises() }; wrapper?.unmount() })

describe('FUP-01 transaction editor protection', () => {
  it('A: blank initialized form cancels without confirmation', async () => {
    await open(); await dialog().find('footer button').trigger('click'); await flushPromises()
    expect(wrapper.find('form.dialog').exists()).toBe(false)
    expect(dialogState.current).toBeNull()
  })
  it.each(['cancel', 'close', 'route'])('B: dirty %s requires confirmation, cancellation preserves all fields', async entry => {
    await open(); await fill()
    let navigation
    if (entry === 'route') navigation = router.push('/orders')
    else if (entry === 'mask') await wrapper.get('.mask').trigger('click')
    else await dialog().get(entry === 'close' ? 'button[aria-label="关闭"]' : 'footer button').trigger('click')
    await flushPromises()
    expect(dialogState.current.title).toBe('未保存修改')
    resolveDialog(false); await flushPromises(); await navigation
    expect(router.currentRoute.value.path).toBe('/transactions')
    expect(dialog().find('input[type="number"]').element.value).toBe('12.34')
    expect(dialog().text()).toContain('SO-FUP')
    const event = new Event('beforeunload', { cancelable: true })
    window.dispatchEvent(event); expect(event.defaultPrevented).toBe(true)
  })
  it('B: clicking the backdrop leaves the dirty form open without prompting', async () => {
    await open(); await fill()
    await wrapper.get('.mask').trigger('click'); await flushPromises()
    expect(dialogState.current).toBeNull()
    expect(dialog().find('input[type="number"]').element.value).toBe('12.34')
    expect(dialog().text()).toContain('SO-FUP')
  })
  it('C: submitting blocks close, mask, new form, route and browser unload', async () => {
    await open(); await fill()
    let reject
    mocks.post.mockImplementationOnce(() => new Promise((_, no) => { reject = no }))
    await dialog().trigger('submit'); await dialog().trigger('submit')
    await wrapper.get('.mask').trigger('click'); await button('新增记账').trigger('click')
    await router.push('/orders')
    expect(mocks.post).toHaveBeenCalledTimes(1)
    expect(dialog().get('button[aria-label="关闭"]').attributes('disabled')).toBeDefined()
    expect(dialog().get('footer button').attributes('disabled')).toBeDefined()
    expect(dialog().get('fieldset').attributes('disabled')).toBeDefined()
    expect(dialogState.current).toBeNull()
    expect(router.currentRoute.value.path).toBe('/transactions')
    const event = new Event('beforeunload', { cancelable: true }); window.dispatchEvent(event); expect(event.defaultPrevented).toBe(true)
    reject({ response: { status: 400, data: { detail: '未写入，金额无效' } } }); await flushPromises()
  })
  it('D/I: definite rejection keeps identity, relations and error; corrected retry succeeds and next form gets new identity', async () => {
    await open(); await fill()
    mocks.post.mockRejectedValueOnce({ response: { status: 400, data: { detail: '未写入，金额无效' } } })
    await submit()
    const payload = mocks.post.mock.calls[0][1]
    expect(payload).toMatchObject({ order: 7, currency: 'USD', amount: 12.34, exchange_rate: 7.123456, notes: '保留备注' })
    expect(dialog().text()).toContain('未写入，金额无效')
    expect(dialog().text()).not.toContain('记账结果尚未确认')
    await dialog().get('button[aria-label="关闭"]').trigger('click'); await flushPromises(); resolveDialog(false); await flushPromises()
    expect(dialog().text()).toContain('未写入，金额无效')
    await dialog().find('input[type="number"]').setValue('20'); await submit()
    expect(mocks.post.mock.calls[1][1]).toMatchObject({ ...payload, amount: 20 })
    expect(wrapper.find('form.dialog').exists()).toBe(false)
    const unload = new Event('beforeunload', { cancelable: true }); window.dispatchEvent(unload); expect(unload.defaultPrevented).toBe(false)
    await open(); await dialog().find('input[type="number"]').setValue('20'); await submit()
    expect(mocks.post.mock.calls.length, wrapper.text()).toBe(3)
    expect(mocks.post.mock.calls[2][1].transaction_no).not.toBe(payload.transaction_no)
  })
  it.each(['close', 'route'])('E/F/G/H: lost response and duplicate rejection remain unknown; %s warns with original number', async entry => {
    await open(); await fill()
    mocks.post.mockRejectedValueOnce(new Error('connection dropped after commit'))
    await submit()
    const payload = mocks.post.mock.calls[0][1]
    expect(dialog().text()).toContain('记账结果尚未确认')
    mocks.post.mockRejectedValueOnce({ response: { status: 400, data: { transaction_no: ['already exists'] } } })
    await submit()
    expect(mocks.post.mock.calls[1][1]).toEqual(payload)
    expect(dialog().text()).toContain('编号重复不代表本次保存成功')
    let navigation
    if (entry === 'route') navigation = router.push('/orders')
    else await dialog().get('button[aria-label="关闭"]').trigger('click')
    await flushPromises()
    expect(dialogState.current.title).toBe('记账结果尚未确认')
    expect(dialogState.current.message).toContain(payload.transaction_no)
    expect(dialogState.current.message).toContain('重新新建可能重复记账')
    resolveDialog(false); await flushPromises(); await navigation
    expect(dialog().get('fieldset').attributes('disabled')).toBeDefined()
    expect(dialog().find('input[type="number"]').element.value).toBe('12.34')
    expect(dialog().text()).toContain('编号重复不代表本次保存成功')
    await button('新增记账').trigger('click')
    expect(dialog().get('fieldset').attributes('disabled')).toBeDefined()
  })
  it('explicit abandonment of an ambiguous request needs the risk acknowledgement', async () => {
    await open(); await fill(); mocks.post.mockRejectedValueOnce({ response: { status: 503, data: { detail: '连接中断' } } }); await submit()
    await dialog().get('footer button').trigger('click'); await flushPromises()
    expect(dialogState.current.confirmText).toBe('已记录编号，放弃表单')
    resolveDialog(true); await flushPromises()
    expect(wrapper.find('form.dialog').exists()).toBe(false)
    expect(mocks.post).toHaveBeenCalledTimes(1)
  })
  it('recovers an unknown receipt after a page reopen and replays the original content', async () => {
    await open(); await fill()
    mocks.post.mockRejectedValueOnce(new Error('connection lost after save'))
    await submit()
    const original = mocks.post.mock.calls[0][1]
    wrapper.unmount()
    wrapper = mount(TransactionPage, { global: { plugins: [router], directives: { 'money-input': {} } } })
    await flushPromises()
    expect(wrapper.text()).toContain('收款结果待确认')
    await button('按原内容核对').trigger('click'); await flushPromises()
    expect(dialog().get('fieldset').attributes('disabled')).toBeDefined()
    mocks.post.mockResolvedValueOnce({ data: { id: 99, transaction_no: original.transaction_no, kind: 'customer_receipt' } })
    await submit()
    expect(mocks.post.mock.calls[1][1]).toEqual(original)
    expect(window.localStorage.getItem(savedKey(`finance-receipt-${original.transaction_no}`))).toBeNull()
  })
  it('reopens an uncertain source refund and retries its original identity and evidence', async () => {
    const row = { id: 71, transaction_no: 'FIN-SYNTH', transaction_date: '2026-10-18', direction: 'income', kind: 'customer_receipt', status: 'confirmed', customer_name: '合成客户', currency: 'USD', amount: '100', refundable_cash_amount: '80', rmb_amount: null, allocations: [{ id: 3, order: 7, contract_no: 'SO-FUP', is_active: true, amount: '100', remaining_amount: '0' }], receipt_refunds: [] }
    const attempt = { key: 'REF-original', payload: { actual_date: '2026-10-18', order: 7, amount: '20', reason: '已核实实际退款凭证', voucher: 5, voucherName: 'refund.pdf' } }
    window.localStorage.setItem(savedKey('finance-refund-71'), JSON.stringify(attempt))
    mocks.listAll.mockImplementation(async url => url === '/transactions/' ? [row] : url === '/orders/' ? [{ id: 7, order_no: 'SO-FUP', customer_name: '合成客户', currency: 'USD', status: 'confirmed' }] : [])
    wrapper.unmount(); wrapper = mount(TransactionPage, { global: { plugins: [router], directives: { 'money-input': {} } } }); await flushPromises()
    await button('详情').trigger('click'); await button('从本笔登记退款').trigger('click'); await flushPromises()
    const form = wrapper.get('form[aria-labelledby="receipt-refund-title"]')
    expect(form.text()).toContain('上次结果待确认')
    expect(form.get('input[type="date"]').element.value).toBe('2026-10-18')
    expect(form.get('fieldset').attributes('disabled')).toBeDefined()
    await form.trigger('submit'); await flushPromises()
    const [url, body, config] = mocks.post.mock.calls.at(-1)
    expect(url).toBe('/transactions/71/refund-cash/')
    expect(body).toEqual({ actual_date: '2026-10-18', order: 7, amount: '20', reason: '已核实实际退款凭证', voucher: 5 })
    expect(config.headers['Idempotency-Key']).toBe('REF-original')
    expect(window.localStorage.getItem(savedKey('finance-refund-71'))).toBeNull()
  })
  it('records an orderless USD receipt with separate discount, fee and plan allocation', async () => {
    mocks.listAll.mockImplementation(async url => url === '/customers/' ? [{ id: 11, name: '合成客户' }] : url === '/payment-plans/' ? [{ id: 31, order: 7, customer_id: 11, direction: 'receivable', currency: 'USD', status: 'open', contract_no: 'SO-FUP', remaining_amount: '1000' }] : [])
    wrapper.unmount(); wrapper = mount(TransactionPage, { global: { plugins: [router], directives: { 'money-input': {} } } }); await flushPromises()
    await open(); await dialog().find('select').setValue('customer_receipt')
    const findLabel = (scope, name) => scope.findAll('label').find(label => label.text().includes(name))
    expect(findLabel(dialog(), '币种').get('select').element.value).toBe('USD')
    await dialog().findAll('label').find(label => label.text().trim().startsWith('客户请选择客户')).get('select').setValue('11'); await flushPromises()
    await findLabel(dialog(), '银行实际到账原币金额').get('input').setValue('985')
    await findLabel(dialog(), '客户实际汇款金额').get('input').setValue('990')
    mocks.post.mockResolvedValueOnce({ data: { id: 51, name: 'bank.pdf' } }).mockResolvedValueOnce({ data: { id: 52, name: 'discount.pdf' } }).mockResolvedValueOnce({ data: { id: 100, transaction_no: 'FIN-TEST', kind: 'customer_receipt' } })
    await button('添加扣减明细').trigger('click')
    let cards = dialog().findAll('.adjustment-card')
    await findLabel(cards[0], '金额').get('input').setValue('5')
    await findLabel(cards[0], '处理方式').get('select').setValue('company')
    await findLabel(cards[0], '原因').get('textarea').setValue('银行凭证证明我方承担')
    let fileInput = findLabel(cards[0], '依据凭证').get('input')
    Object.defineProperty(fileInput.element, 'files', { value: [new File(['proof'], 'bank.pdf')], configurable: true }); await fileInput.trigger('change')
    await cards[0].findAll('button').find(b => b.text() === '上传凭证').trigger('click'); await flushPromises()
    await button('添加扣减明细').trigger('click'); cards = dialog().findAll('.adjustment-card')
    await findLabel(cards[1], '性质').get('select').setValue('discount')
    await findLabel(cards[1], '金额').get('input').setValue('10')
    await findLabel(cards[1], '处理方式').get('select').setValue('applied')
    await findLabel(cards[1], '关联应收计划').get('select').setValue('31')
    await findLabel(cards[1], '原因').get('textarea').setValue('客户已授权优惠减免')
    fileInput = findLabel(cards[1], '依据凭证').get('input')
    Object.defineProperty(fileInput.element, 'files', { value: [new File(['proof'], 'discount.pdf')], configurable: true }); await fileInput.trigger('change')
    await cards[1].findAll('button').find(b => b.text() === '上传凭证').trigger('click'); await flushPromises()
    await button('分配到多张订单').trigger('click')
    const allocationRow = dialog().get('.receipt-allocation-row')
    await findLabel(allocationRow, '订单应收计划').get('select').setValue('31')
    await findLabel(allocationRow, '本次核销金额').get('input').setValue('990')
    await submit()
    const body = mocks.post.mock.calls.at(-1)[1]
    expect(body).toMatchObject({ kind: 'customer_receipt', customer: 11, order: null, currency: 'USD', amount: 985, remittance_amount: 990, receipt_adjustments: [{ nature: 'bank_fee', amount: 5, handling: 'company', evidence: 51 }, { nature: 'discount', amount: 10, handling: 'applied', evidence: 52, plan: 31 }], plan_allocations: [{ plan: 31, amount: 990 }] })
    expect(body).not.toHaveProperty('exchange_rate')
  })
  it('keeps entered receipt amounts until a currency change is explicitly confirmed', async () => {
    await open(); await dialog().find('select').setValue('customer_receipt')
    const amount = dialog().findAll('label').find(label => label.text().includes('银行实际到账原币金额')).get('input')
    const currency = dialog().findAll('label').find(label => label.text().startsWith('币种')).get('select')
    await amount.setValue('985'); await currency.setValue('CNY')
    expect(dialog().text()).toContain('切换到 CNY 会清空')
    expect(amount.element.value).toBe('985'); expect(currency.element.value).toBe('USD')
    await button('取消').trigger('click')
    expect(amount.element.value).toBe('985'); expect(currency.element.value).toBe('USD')
    await currency.setValue('CNY'); await button('确认变更并清空相关输入').trigger('click')
    expect(amount.element.value).toBe(''); expect(currency.element.value).toBe('CNY')
  })
})
